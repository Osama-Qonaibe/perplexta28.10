export interface StudioTemplate {
  id: string;
  titleAr: string;
  titleEn: string;
  category: 'social' | 'marketing' | 'quotes' | 'fitness' | 'fashion' | 'tech' | 'story' | 'banner' | 'real_estate' | 'menu' | 'community' | 'posts';
  thumbnailUrl: string;
  backgroundColor: string;
  backgroundImage?: string;
  canvasBackground?: string;
  width: number;
  height: number;
  aspectRatio: '1:1' | '9:16' | '16:9' | '1.91:1' | '4:5';
  elements: CanvasElement[];
  creatorName?: string;
  creatorAvatar?: string;
  creatorUsername?: string;
  rating?: number;
  usesCount?: number;
  previewVideoUrl?: string;
  videoUrl?: string;
}

export function convertMarketplaceToStudioTemplate(tpl: any): StudioTemplate {
  let width = 1080;
  let height = 1080;
  if (tpl.dimensions) {
    const parts = tpl.dimensions.split(/[\s×xX]+/);
    if (parts.length >= 2) {
      const w = parseInt(parts[0], 10);
      const h = parseInt(parts[1], 10);
      if (!isNaN(w) && w > 0) width = w;
      if (!isNaN(h) && h > 0) height = h;
    }
  }

  let aspectRatio: '1:1' | '9:16' | '16:9' | '1.91:1' | '4:5' = '1:1';
  const ratio = width / height;
  if (Math.abs(ratio - 9/16) < 0.1 || height > width * 1.5) {
    aspectRatio = '9:16';
  } else if (Math.abs(ratio - 16/9) < 0.1 || width > height * 1.5) {
    aspectRatio = '16:9';
  } else if (Math.abs(ratio - 4/5) < 0.1) {
    aspectRatio = '4:5';
  } else if (Math.abs(ratio - 1.91) < 0.1) {
    aspectRatio = '1.91:1';
  }

  const fallbackThumb = 'https://images.unsplash.com/photo-1618005182384-a83a8bd57fbe?auto=format&fit=crop&w=600&q=80';
  const resolvedThumb = tpl.thumbnail || tpl.thumbnailUrl || fallbackThumb;
  const resolvedVideo = tpl.videoUrl || tpl.previewVideoUrl || undefined;

  const hasElements = Boolean(tpl.elements && Array.isArray(tpl.elements) && tpl.elements.length > 0);
  const rawBg = tpl.backgroundImage || (tpl.canvasBackground && typeof tpl.canvasBackground === 'string' && !tpl.canvasBackground.startsWith('#') && !tpl.canvasBackground.startsWith('rgb') && !tpl.canvasBackground.startsWith('hsl') ? tpl.canvasBackground : undefined);
  const resolvedBgImage = (rawBg && rawBg !== resolvedThumb) ? rawBg : (hasElements ? undefined : resolvedThumb);
  const resolvedBgColor = (tpl.canvasBackground && (tpl.canvasBackground.startsWith('#') || tpl.canvasBackground.startsWith('rgb') || tpl.canvasBackground.startsWith('hsl')))
    ? tpl.canvasBackground
    : (tpl.backgroundColor || '#090d16');

  return {
    id: tpl.id,
    titleAr: tpl.titleAr || tpl.title || 'قالب رينكس',
    titleEn: tpl.titleEn || tpl.title || 'Rinex Template',
    category: tpl.category || 'community',
    thumbnailUrl: resolvedThumb,
    previewVideoUrl: resolvedVideo,
    backgroundColor: resolvedBgColor,
    backgroundImage: resolvedBgImage,
    canvasBackground: tpl.canvasBackground || resolvedBgColor,
    width,
    height,
    aspectRatio,
    elements: tpl.elements || [],
    creatorName: tpl.creatorName,
    creatorAvatar: tpl.creatorAvatar,
    creatorUsername: tpl.creatorUsername,
    rating: tpl.rating,
    usesCount: tpl.usesCount
  };
}

